-- Allow AI Agents to send messages by removing the foreign key constraint on sender_id
-- This is necessary because sender_id can refer to either:
--   1. users.id (for regular user messages)
--   2. ai_agents.id (for AI-generated messages)
-- PostgreSQL doesn't support polymorphic foreign keys, so we remove the constraint
-- and rely on application-level validation instead.

-- Drop the existing foreign key constraint
ALTER TABLE messages DROP CONSTRAINT IF EXISTS messages_sender_id_fkey;

-- Drop the foreign key constraint on receiver_id as well for consistency
-- (receiver_id should still only be user IDs, but we'll validate at application level)
ALTER TABLE messages DROP CONSTRAINT IF EXISTS messages_receiver_id_fkey;

-- Update comments to reflect the new behavior
COMMENT ON COLUMN messages.sender_id IS 'UUID of the message sender. Can be either a user ID (users.id) or an AI Agent ID (ai_agents.id). Check is_ai_generated to determine the type.';
COMMENT ON COLUMN messages.receiver_id IS 'UUID of the message receiver (for private messages). Should be a user ID (users.id). NULL for group messages.';
COMMENT ON COLUMN messages.is_ai_generated IS 'TRUE if message was generated by an AI Agent. In this case, sender_id refers to ai_agents.id instead of users.id';

-- Add indexes to help with queries
CREATE INDEX IF NOT EXISTS idx_messages_ai_generated 
    ON messages(is_ai_generated, group_id, timestamp DESC) 
    WHERE is_ai_generated = TRUE;

COMMENT ON INDEX idx_messages_ai_generated IS 'Index for querying AI-generated messages in groups';
